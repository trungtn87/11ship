  async function registerFood(): Promise<{ phone: Phone; native: NativePhone; token: string; userId: string; bindingId: string; response: ApiResponse; registration: { token: string; keyId: string }; idempotencyKey: string }> {
    const phone = randomPhone();
    app.track(phone.normalized);
    const native = phoneOf();
    const enrolled = await native.enroll('FOOD');
    expect(enrolled.response.status).toBe(201);
    const registration = { token: enrolled.token, keyId: enrolled.keyId };
    const idempotencyKey = randomUUID();
    const result = await native.authCall('FOOD', '/client-auth/register', registerBody(phone, 'FOOD'), registration, { idempotencyKey });
    expect(result.response.status).toBe(201);
    const data = dataOf(result.response);
    const bindingId = String(result.response.headers.get('x-device-binding-id'));
    native.bindingId = bindingId;
    return { phone, native, token: String(data.access_token), userId: String(data.user_id), bindingId, response: result.response, registration, idempotencyKey };
  }

  /** Login of the same user from an app (enrolling or joining first). */
  async function login(native: NativePhone, phone: Phone, which: 'FOOD' | 'SHIP', mode: 'ENROLL' | 'AUTH' | { join: string; authorizer: 'FOOD' | 'SHIP' }): Promise<{ response: ApiResponse; token: string; registration: { token: string; keyId: string } }> {
    let registration: { token: string; keyId: string };
    if (mode === 'ENROLL') {
      const enrolled = await native.enroll(which);
      expect(enrolled.response.status).toBe(201);
      registration = { token: enrolled.token, keyId: enrolled.keyId };
    } else if (mode === 'AUTH') {
      const again = await native.reauth(which);
      expect(again.response.status).toBe(201);
      registration = { token: again.token, keyId: native.keys[which]?.keyId ?? '' };
    } else {
      const authorizer = native.keys[mode.authorizer];
      if (authorizer === undefined) {
        throw new Error('no authorizer');
      }
      const joined = await native.join(which, mode.join, authorizer);
      expect(joined.response.status).toBe(201);
      registration = { token: joined.token, keyId: joined.keyId };
    }
    const result = await native.authCall(which, '/client-auth/login', loginBody(phone, which), registration);
    const token = typeof result.response.body.data?.access_token === 'string' ? result.response.body.data.access_token : '';
    return { response: result.response, token, registration };
  }

