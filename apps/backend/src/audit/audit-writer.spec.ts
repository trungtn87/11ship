import { describe, expect, it } from '@jest/globals';
import { TechnicalError } from '../common/app-errors';
import { JsonValidationError } from '../shared/json/safe-json';
import { codeOf } from '../shared/source-scan.fixture';
import { QueryRows, TransactionContext } from '../transaction/transaction-context';
import { AuditEntry, AuditEntryError } from './audit-entry';
import { AuditWriter } from './audit-writer';

const REQUEST_ID = '3f2b8c1e-9d4a-4b6f-8a21-5c7e0d9f1a34';
const UUID = /^[0-9a-f]{8}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{4}-[0-9a-f]{12}$/;

interface Call {
  readonly text: string;
  readonly values: readonly unknown[] | undefined;
}

/** A scripted context: records every statement and answers with a configurable row count. */
function fakeContext(rowCount: number | null = 1, failure?: unknown): { context: TransactionContext; calls: Call[] } {
  const calls: Call[] = [];
  const context: TransactionContext = {
    isActive: true,
    query<R extends object = Record<string, unknown>>(text: string, values?: readonly unknown[]): Promise<QueryRows<R>> {
      calls.push({ text, values });
      if (failure !== undefined) {
        return Promise.reject(failure);
      }
      return Promise.resolve({ rows: [], rowCount } as QueryRows<R>);
    },
  };
  return { context, calls };
}

function entry(overrides: Record<string, unknown> = {}): AuditEntry {
  return {
    requestId: REQUEST_ID,
    actorType: 'USER',
    actorId: 'u-1',
    action: 'auth.register.v1',
    resourceType: 'user',
    resourceId: 'u-1',
    resourceVersion: 3,
    outcome: 'SUCCESS',
    metadata: { step: 'created', b: 1 },
    ...overrides,
  } as AuditEntry;
}

describe('AuditWriter.append — one INSERT inside the caller transaction', () => {
  it('sends exactly one statement through the context, with the prepared values in column order', async () => {
    const { context, calls } = fakeContext();
    await new AuditWriter().append(context, entry());

    expect(calls).toHaveLength(1);
    const [call] = calls as [Call];
    expect(call.text).toContain('INSERT INTO app.audit_logs');
    const values = call.values as unknown[];
    expect(values).toHaveLength(11);
    expect(values[0]).toMatch(UUID); // audit_id, generated by the writer
    expect(values.slice(1)).toEqual([
      REQUEST_ID,
      'USER',
      'u-1',
      'auth.register.v1',
      'user',
      'u-1',
      3,
      'SUCCESS',
      null,
      '{"b":1,"step":"created"}', // canonical metadata
    ]);
  });

  it('turns every absent optional field into NULL and an absent metadata into {}', async () => {
    const { context, calls } = fakeContext();
    await new AuditWriter().append(context, {
      requestId: REQUEST_ID,
      actorType: 'ANONYMOUS',
      action: 'auth.login.v1',
      outcome: 'DENIED',
      reasonCode: 'INVALID_CREDENTIALS',
    });
    const values = (calls[0] as Call).values as unknown[];
    expect(values.slice(1)).toEqual([
      REQUEST_ID,
      'ANONYMOUS',
      null,
      'auth.login.v1',
      null,
      null,
      null,
      'DENIED',
      'INVALID_CREDENTIALS',
      '{}',
    ]);
  });

  it('generates a fresh audit id per row', async () => {
    const { context, calls } = fakeContext();
    const writer = new AuditWriter();
    await writer.append(context, entry());
    await writer.append(context, entry());
    const [first, second] = calls.map((call) => (call.values as unknown[])[0]);
    expect(first).not.toBe(second);
  });

  it('takes the timestamp from the PostgreSQL clock inside the statement, never from the application', async () => {
    const { context, calls } = fakeContext();
    await new AuditWriter().append(context, entry());
    const text = (calls[0] as Call).text;
    expect(text).toContain("date_trunc('milliseconds', clock_timestamp())");
    // occurred_at is not a bound parameter: nothing the application knows can end up in it.
    expect(((calls[0] as Call).values as unknown[]).some((value) => value instanceof Date)).toBe(false);

    const code = codeOf('audit/audit-writer.ts');
    expect(code).not.toMatch(/Date\.now|new Date|performance\.now|hrtime/);
  });

  it('accepts a seam for the audit id (used by tests to force a real primary-key collision)', async () => {
    const { context, calls } = fakeContext();
    await new AuditWriter({ idGenerator: () => '11111111-1111-4111-8111-111111111111' }).append(context, entry());
    expect(((calls[0] as Call).values as unknown[])[0]).toBe('11111111-1111-4111-8111-111111111111');
  });
});

describe('AuditWriter.append — validation happens BEFORE any statement', () => {
  const invalid: Array<[string, Record<string, unknown>]> = [
    ['an unsafe metadata key (password)', { metadata: { password: 'x' } }],
    ['a nested secret key (access_token)', { metadata: { a: { b: [{ access_token: 'x' }] } } }],
    ['authorization', { metadata: { Authorization: 'Bearer x' } }],
    ['cookie', { metadata: { cookie: 'x' } }],
    ['database_url', { metadata: { database_url: 'postgres://x' } }],
    ['oversized metadata', { metadata: { a: 'x'.repeat(8 * 1024) } }],
    ['a request id that is not a UUID', { requestId: 'req-1' }],
    ['a URL as action', { action: '/api/register' }],
    ['a DENIED entry without a reason', { outcome: 'DENIED' }],
    ['a resource id without a resource type', { resourceType: null, resourceVersion: null }],
    ['a request DTO field', { body: { phone: '0901' } }],
  ];

  it.each<[string, Record<string, unknown>]>(invalid)('rejects %s without sending any statement', async (_label, overrides) => {
    const { context, calls } = fakeContext();
    const failure = await new AuditWriter().append(context, entry(overrides)).then(
      () => undefined,
      (error: unknown) => error,
    );
    expect(failure instanceof AuditEntryError || failure instanceof JsonValidationError).toBe(true);
    expect(calls).toHaveLength(0);
  });
});

describe('AuditWriter.append — failures are thrown, never swallowed', () => {
  it('propagates a database error unchanged so the outer transaction rolls back', async () => {
    const dbError = Object.assign(new Error('duplicate key'), { code: '23505', severity: 'ERROR' });
    const { context } = fakeContext(1, dbError);
    const thrown = await new AuditWriter().append(context, entry()).then(
      () => undefined,
      (error: unknown) => error,
    );
    expect(thrown).toBe(dbError);
  });

  it('fails when the INSERT reports anything other than exactly one row', async () => {
    for (const rowCount of [0, 2, null]) {
      const { context } = fakeContext(rowCount);
      const thrown = await new AuditWriter().append(context, entry()).then(
        () => undefined,
        (error: unknown) => error,
      );
      expect(thrown instanceof TechnicalError).toBe(true);
    }
  });

  it('refuses a closed context through the context itself (no statement reaches a client)', async () => {
    const closed: TransactionContext = {
      isActive: false,
      query: () => Promise.reject(new TechnicalError('internal', 'Transaction failed (CONTEXT_CLOSED)')),
    };
    const thrown = await new AuditWriter().append(closed, entry()).then(
      () => undefined,
      (error: unknown) => error,
    );
    expect(thrown instanceof TechnicalError).toBe(true);
  });
});

describe('AuditWriter — participant only', () => {
  it('has no injectable dependency and no standalone mode', () => {
    expect(AuditWriter.length).toBe(0);
    expect(Object.getOwnPropertyNames(AuditWriter.prototype).sort()).toEqual(['append', 'constructor']);
  });

  it('never imports a pool or a transaction manager and never controls a transaction', () => {
    const code = codeOf('audit/audit-writer.ts');
    expect(code).not.toMatch(/from 'pg'/);
    expect(code).not.toMatch(/TransactionManager|withTransaction|PoolClient|\bPool\b/);
    expect(code).not.toMatch(/\bBEGIN\b|\bCOMMIT\b|\bROLLBACK\b|SAVEPOINT/);
    expect(code).not.toMatch(/TransactionClientSource|release\(/);
  });
});
